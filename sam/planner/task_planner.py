"""
SAM - Task Planner & Goal Decomposition Engine
Transforms natural language objectives into verifiable, step-by-step Task plans.
Uses local LLM (qwen3:4b) when Ollama is online; transparently reports fallback to verified schemas when offline.
"""

from typing import Any, List, Dict
import re
import uuid
import time
import json
import logging

from sam.agent.models import (
    Task,
    TaskStep,
    TaskStatus,
    StepStatus,
    RiskLevel,
    VerificationResult,
)
from sam.tools.registry import tool_registry
from sam.agent.models_provider import model_manager
from sam.config.settings import settings

logger = logging.getLogger("sam.planner")


class TaskPlanner:
    """Interprets objectives and produces structured, executable, verifiable task plans."""

    def __init__(self, model_mgr=None):
        self.model_manager = model_mgr or model_manager

    def plan(self, objective: str, context: dict[str, Any] | None = None) -> Task:
        context = context or {}
        objective_clean = objective.strip()
        task = Task(
            task_id=f"sam_task_{int(time.time())}_{str(uuid.uuid4())[:4]}",
            objective=objective_clean,
            status=TaskStatus.PLANNING,
            context_data=context,
        )

        # 1. Check if deterministic schema is explicitly requested via context
        use_deterministic = context.get("deterministic", False)

        # 2. Attempt LLM Planning if local model is online and not forced deterministic
        steps = None
        if not use_deterministic and self.model_manager.is_available():
            logger.info("Local LLM runtime is ONLINE. Requesting plan from local model...")
            tools_catalog = tool_registry.list_tools()
            res = self.model_manager.generate_plan(objective_clean, tools_catalog)
            if res:
                llm_response, model_used = res
                steps = self._parse_llm_plan(llm_response)
                if steps:
                    task.context_data["planned_by"] = f"LLM ({model_used})"
                    task.context_data["llm_used"] = True
                    logger.info(f"Successfully generated task plan using local LLM ({len(steps)} steps via {model_used}).")

        # 3. Transparent fallback when local LLM is offline or deterministic mode is active
        if not steps:
            if not use_deterministic:
                task.context_data["planned_by"] = "DETERMINISTIC_SCHEMA_FALLBACK"
                task.context_data["llm_used"] = False
                task.context_data["llm_status"] = "UNAVAILABLE (Ollama offline on 127.0.0.1:11434)"
                logger.info(
                    "Local inference runtime is UNAVAILABLE. "
                    "Decomposing objective using verified built-in deterministic schemas."
                )
            else:
                task.context_data["planned_by"] = "VERIFIED_WORKFLOW_SCHEMA"
                task.context_data["llm_used"] = False
            steps = self._decompose_deterministic(objective_clean, context)

        task.steps = steps
        task.status = TaskStatus.PENDING
        return task

    def _parse_llm_plan(self, raw_json_str: str) -> List[TaskStep] | None:
        """Parses structured JSON step list generated by local LLM."""
        try:
            # Strip thinking block <think> ... </think> if generated by Qwen3 Thinking model
            clean = re.sub(r"<think>[\s\S]*?</think>", "", raw_json_str).strip()
            # Strip markdown code blocks if model returned ```json ... ```
            if "```" in clean:
                match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", clean)
                if match:
                    clean = match.group(1).strip()
                else:
                    clean = re.sub(r"^```[a-zA-Z]*\n?", "", clean)
                    clean = re.sub(r"\n?```$", "", clean)
            # Find the JSON array [ ... ] if there is conversational preamble/postscript
            bracket_match = re.search(r"\[\s*\{[\s\S]*\}\s*\]", clean)
            if bracket_match:
                clean = bracket_match.group(0).strip()
            data = json.loads(clean)
            if isinstance(data, list):
                steps = []
                for idx, item in enumerate(data):
                    risk_str = item.get("risk_level", "LOW").upper()
                    risk = RiskLevel[risk_str] if risk_str in RiskLevel.__members__ else RiskLevel.LOW
                    steps.append(TaskStep(
                        step_index=idx,
                        title=item.get("title", f"Step {idx+1}"),
                        description=item.get("description", ""),
                        tool_name=item.get("tool_name", ""),
                        tool_args=item.get("tool_args", {}),
                        risk_level=risk,
                        verification_criteria=item.get("verification_criteria", "Operation completed with success=True."),
                    ))
                return steps
        except Exception as e:
            logger.warning(f"Failed to parse LLM JSON plan: {e}")
        return None

    def _decompose_deterministic(self, objective: str, context: dict[str, Any]) -> list[TaskStep]:
        obj_lower = objective.lower()

        # Workflow D: Hardware & System Telemetry
        if any(w in obj_lower for w in ["hardware", "cpu", "gpu", "ram", "disk usage", "usage", "telemetry"]):
            return [
                TaskStep(
                    step_index=0,
                    title="Inspect Hardware Counters",
                    description="Query CPU, system RAM, NVIDIA GPU VRAM, and disk storage metrics.",
                    tool_name="system_get_telemetry",
                    tool_args={},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Telemetry report contains valid CPU, RAM, GPU, and Disk stats.",
                ),
                TaskStep(
                    step_index=1,
                    title="Analyze Telemetry & Diagnose Issues",
                    description="Evaluate if any resource is under thermal, memory, or capacity strain.",
                    tool_name="system_analyze_health",
                    tool_args={},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Diagnosis provides clear health explanation for user's OMEN 16.",
                )
            ]

        # Workflow A: Coding Workflow (VS Code / Python script / run / fix)
        elif any(w in obj_lower for w in ["python project", "coding", "write a script", "vs code", "fix errors"]):
            ws_name = context.get("project_name", "sam_python_demo")
            fname = context.get("filename", "main.py")
            return [
                TaskStep(
                    step_index=0,
                    title="Inspect or Initialize Project Workspace",
                    description="Check target coding directory and structure.",
                    tool_name="coding_inspect_workspace",
                    tool_args={"workspace_name": ws_name},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Workspace path exists and is accessible.",
                ),
                TaskStep(
                    step_index=1,
                    title="Create Python Source Code",
                    description="Write script files according to the user specification.",
                    tool_name="coding_write_file",
                    tool_args={
                        "workspace_name": ws_name,
                        "filename": fname,
                        "content": context.get("code_content", ""),
                    },
                    risk_level=RiskLevel.MEDIUM,
                    verification_criteria="Target Python file exists on disk with non-zero size.",
                ),
                TaskStep(
                    step_index=2,
                    title="Execute Script and Capture Output",
                    description="Run the Python script in isolated process and capture stdout/stderr.",
                    tool_name="coding_run_script",
                    tool_args={"workspace_name": ws_name, "filename": fname},
                    risk_level=RiskLevel.MEDIUM,
                    verification_criteria="Process execution finishes with exit code and readable output.",
                ),
                TaskStep(
                    step_index=3,
                    title="Verify Execution Results",
                    description="Analyze stdout for expected output or tracebacks; auto-debug if needed.",
                    tool_name="coding_verify_results",
                    tool_args={"workspace_name": ws_name, "filename": fname},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Script succeeds without unhandled exceptions.",
                )
            ]

        # Workflow B: Video Editing Workflow
        elif any(w in obj_lower for w in ["video", "subtitles", "1080p", "vertical", "davinci", "clip"]):
            return [
                TaskStep(
                    step_index=0,
                    title="Inspect Source Video Footage",
                    description="Validate input media format, duration, audio streams, and resolution.",
                    tool_name="video_inspect_media",
                    tool_args={"input_path": context.get("video_input", "")},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Source video exists, is readable, and metadata extracted.",
                ),
                TaskStep(
                    step_index=1,
                    title="Configure Video Timeline & Transformations",
                    description="Setup vertical 9:16 crop/pad to 1080x1920 and audio normalization.",
                    tool_name="video_configure_pipeline",
                    tool_args={
                        "target_aspect": "9:16",
                        "target_height": 1920,
                        "normalize_audio": True,
                    },
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Video pipeline configuration validated.",
                ),
                TaskStep(
                    step_index=2,
                    title="Generate Subtitles / Captions",
                    description="Extract audio track and transcribe speech timestamps.",
                    tool_name="video_generate_subtitles",
                    tool_args={"language": "en"},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="SRT/VTT subtitle stream generated with valid timecodes.",
                ),
                TaskStep(
                    step_index=3,
                    title="Render and Export Output Video",
                    description="Render new vertical 1080p video to output destination without touching source.",
                    tool_name="video_export_render",
                    tool_args={"output_folder": context.get("output_folder", "")},
                    risk_level=RiskLevel.MEDIUM,
                    verification_criteria="Exported video file exists, is non-zero, and has correct resolution.",
                ),
                TaskStep(
                    step_index=4,
                    title="Verify Video Export Integrity",
                    description="Inspect rendered video duration and visual frames to confirm quality.",
                    tool_name="video_verify_export",
                    tool_args={},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Exported video plays smoothly without corrupt frames.",
                )
            ]

        # Workflow C: Browser Autonomous Research
        elif any(w in obj_lower for w in ["browser", "research", "web", "scrape", "search online"]):
            return [
                TaskStep(
                    step_index=0,
                    title="Launch Browser Session",
                    description="Start browser session safely in isolated context.",
                    tool_name="browser_open",
                    tool_args={"url": context.get("url", "https://en.wikipedia.org")},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Browser window is active and navigation succeeds.",
                ),
                TaskStep(
                    step_index=1,
                    title="Navigate & Extract Information",
                    description="Query target research keywords and extract structured page content.",
                    tool_name="browser_extract_content",
                    tool_args={"query": objective},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Extracted text contains relevant query terms.",
                ),
                TaskStep(
                    step_index=2,
                    title="Compile Research Summary Report",
                    description="Organize gathered insights into a structured markdown report.",
                    tool_name="document_create_report",
                    tool_args={"title": f"Research Report - {objective[:40]}"},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Report file created with executive summary and key findings.",
                )
            ]

        # Workflow E: Document & PDF Intelligence
        elif any(w in obj_lower for w in ["pdf", "document", "summarize", "docx", "xlsx"]):
            return [
                TaskStep(
                    step_index=0,
                    title="Inspect and Extract Document Text",
                    description="Read PDF/DOCX structure, text segments, and metadata.",
                    tool_name="document_read",
                    tool_args={"file_path": context.get("file_path", "")},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Document parsed and text extracted.",
                ),
                TaskStep(
                    step_index=1,
                    title="Analyze and Summarize Content",
                    description="Generate key summaries, extract action items, and prepare Q&A index.",
                    tool_name="document_summarize",
                    tool_args={},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Summary synthesized with key takeaways.",
                )
            ]

        # Generic Computer-Use Task Fallback
        else:
            return [
                TaskStep(
                    step_index=0,
                    title="Observe Active Desktop State",
                    description="Capture current screenshot, active window, and visible UI controls.",
                    tool_name="computer_observe_desktop",
                    tool_args={},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Observation record captured with window title and image hash.",
                ),
                TaskStep(
                    step_index=1,
                    title=f"Execute Planned Operation for: {objective[:50]}",
                    description="Perform required UI or tool actions to accomplish the goal.",
                    tool_name="computer_execute_intent",
                    tool_args={"intent": objective},
                    risk_level=RiskLevel.MEDIUM,
                    verification_criteria="Action changes detected on screen or in system state.",
                ),
                TaskStep(
                    step_index=2,
                    title="Verify Final State",
                    description="Re-observe desktop and confirm outcome matches objective.",
                    tool_name="computer_verify_state",
                    tool_args={"objective": objective},
                    risk_level=RiskLevel.LOW,
                    verification_criteria="Verification confirms completed goal.",
                )
            ]


task_planner = TaskPlanner()
